name = "hello Alice"

print(len(name)) # ye function string ki length ko count karta hai.
print(name.upper()) # ye function string ko uppercase me convert karta hai.
print(name.lower()) # ye function string ko lowercase me convert karta hai.
print(name.replace("Alice", "Bob")) # ye function string me kisi bhi word ko replace karne ke liye use hota hai.
print(name.endswith("ice")) # ye function check karta hai ki string ka end word kya hai. agar end word match hota hai to True return karega otherwise False.
print(name.startswith("hel")) # ye function check karta hai ki string ka start word kya hai. agar start word match hota hai to True return karega otherwise False.
print(name.capitalize()) # ye function string ke first letter ko capital letter me convert karta hai.